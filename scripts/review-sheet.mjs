// Writes docs/SPECIES-REVIEW.md: one row per species with the facts a reviewer must check.
// Run: node scripts/review-sheet.mjs
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { ALL_SPECIES as WILDLIFE_DB, ZOO_REGIONS } from "../src/data/species.js";

const photos = JSON.parse(readFileSync("src/data/photos.json", "utf8"));
const focus = JSON.parse(readFileSync("scripts/photo-focus.json", "utf8"));
const n = (x) => Number(x).toLocaleString("en-US");
let out = `# Species review sheet

Generated by \`node scripts/review-sheet.mjs\`. ${WILDLIFE_DB.length} species.

For each animal a second person should check: the photo is the right animal and the close-up is fair;
the four clues are true and do not name it; the population figure, year and band match the linked source;
the range matches a trusted range map. Record sign-offs in \`REVIEWED\` in \`src/data/speciesExtra.js\`.

"Close-up" says whether someone has chosen where the first zoomed-in view centres. "centre" means nobody has,
so the first view may show background or give the animal away.
`;
for (const region of ZOO_REGIONS) {
  const here = WILDLIFE_DB.filter(a => a.region === region);
  out += `\n## ${region} (${here.length})\n\n| Animal | Status | Population shown | Scores full marks | Year | Confidence | Source | Photo credit | Close-up |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n`;
  for (const a of here) {
    const p = a.population, ph = photos[a.id];
    out += `| ${a.name}${a.practice ? " (practice only)" : ""} | ${a.status} | ${p.display} | ${n(p.low)} – ${n(p.high)} | ${p.year} | ${p.confidence} | [${p.source.label.replace(/\|/g, "/")}](${p.source.url}) | [${ph.artist.replace(/\|/g, "/").slice(0, 40)}](${ph.sourceUrl}), ${ph.license} | ${focus[a.id]?.focus ? "chosen" : "centre"} |\n`;
  }
}
mkdirSync("docs", { recursive: true });
writeFileSync("docs/SPECIES-REVIEW.md", out);
const rough = WILDLIFE_DB.filter(a => a.population.confidence === "rough").length;
console.log(`docs/SPECIES-REVIEW.md written: ${WILDLIFE_DB.length} species, ${rough} with rough populations, ${WILDLIFE_DB.filter(a => !focus[a.id]?.focus).length} without a chosen close-up.`);
